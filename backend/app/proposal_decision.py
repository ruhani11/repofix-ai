"""Human review decisions bound to immutable proposal bytes; no execution.

The future authenticated service must load ProposalStore.get(identity.id, id)
before calling bind_proposal_decision. ProposalResponse has no owner field, so
this pure binder cannot independently establish ownership or human intent.
It returns an unsaved decision record, not a capability token or execution result.
"""

from datetime import datetime, timezone
import json
from typing import Literal
from uuid import uuid4

from pydantic import BaseModel, ConfigDict, Field, TypeAdapter, ValidationError, field_validator
from pydantic_core import PydanticSerializationError

from app.fix_proposal import _source_text
from app.github_client import SHA_PATTERN
from app.github_oauth import GitHubIdentity
from app.investigation_runner import InvestigationEvent
from app.proposal_history import Digest, Identifier, ProposalResponse


ReviewDecision = Literal["approve_for_validation", "reject"]
_EVENTS = TypeAdapter(list[InvestigationEvent])
_DETAILS = {
    "invalid_identity": "A valid authenticated GitHub identity is required.",
    "invalid_input": "The proposal review decision is invalid.",
    "invalid_proposal": "The saved proposal could not be verified for review.",
    "not_saved": "Save the proposal before recording a review decision.",
    "proposal_changed": "The reviewed proposal, base commit or patch hash does not match.",
    "invalid_time": "A valid review time at or after proposal creation is required.",
}


class ProposalDecisionError(RuntimeError):
    """Safe stable reason; never includes source, comments or raw validation errors."""

    def __init__(self, code: str):
        self.code = code
        super().__init__(_DETAILS.get(code, "The proposal decision could not be prepared."))


class _DecisionModel(BaseModel):
    model_config = ConfigDict(strict=True, extra="forbid", frozen=True, hide_input_in_errors=True)


class ProposalDecisionInput(_DecisionModel):
    """Explicit human action, with the exact proposal/base/hash they reviewed.

    approve_for_validation is limited to the future bounded sandbox validation
    workflow. It does not approve publishing, a target-branch write or a PR.
    No decision is defaulted, generated by an agent or inferred from proposal_saved.
    """

    proposal_id: Identifier
    base_commit_sha: str = Field(pattern=SHA_PATTERN)
    patch_sha256: Digest
    decision: ReviewDecision
    comment: str | None = Field(default=None, max_length=2000)

    @field_validator("comment")
    @classmethod
    def clean_comment(cls, value):
        if value is None:
            return None
        return _source_text(value).strip() or None


class ProposalDecision(_DecisionModel):
    """Server-built review event, not proof of saving, test success or active consent.

    A later service must persist decisions account-scoped and define their
    current/revoked state before a sandbox consumes one. Execution still needs
    a server-owned restricted runtime profile; this contract starts no work.
    """

    decision_id: Identifier
    proposal_id: Identifier
    investigation_run_id: Identifier
    account_id: int = Field(gt=0, le=2**63 - 1)
    repository_id: int = Field(gt=0, le=2**63 - 1)
    repository_full_name: str = Field(min_length=3, max_length=201)
    base_commit_sha: str = Field(pattern=SHA_PATTERN)
    tree_sha: str = Field(pattern=SHA_PATTERN)
    patch_sha256: Digest
    decision: ReviewDecision
    created_at: datetime
    comment: str | None = Field(default=None, max_length=2000)

    @field_validator("created_at")
    @classmethod
    def require_aware_time(cls, value):
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("A timezone-aware decision time is required.")
        return value.astimezone(timezone.utc)

    @field_validator("comment")
    @classmethod
    def clean_comment(cls, value):
        return ProposalDecisionInput.clean_comment(value)


def bind_proposal_decision(
    identity: GitHubIdentity,
    proposal: ProposalResponse,
    payload: ProposalDecisionInput,
    *,
    now: datetime | None = None,
) -> ProposalDecision:
    """Revalidate server-loaded data and bind a human request to its exact draft.

    now is an internal test/clock seam, never a browser-provided field. Ownership
    lookup, session/CSRF, persistence, revocation/current-state handling and HTTP
    routes belong to the later service. This function performs no I/O or AI work.
    """
    try:
        if not isinstance(identity, GitHubIdentity):
            raise ValueError()
        identity = GitHubIdentity.model_validate(identity.model_dump(warnings="error"))
        if not 0 < identity.id <= 2**63 - 1:
            raise ValueError()
    except (ValidationError, PydanticSerializationError, ValueError, TypeError):
        raise ProposalDecisionError("invalid_identity") from None

    try:
        if not isinstance(payload, ProposalDecisionInput):
            raise ValueError()
        payload = ProposalDecisionInput.model_validate(payload.model_dump(warnings="error"))
    except (ValidationError, PydanticSerializationError, ValueError, TypeError):
        raise ProposalDecisionError("invalid_input") from None

    try:
        if not isinstance(proposal, ProposalResponse):
            raise ValueError()
        data = proposal.model_dump(warnings="error")
        # Rebuild event dataclasses without coercing the other strict Python fields.
        data["events"] = _EVENTS.validate_json(json.dumps(data.get("events")), strict=True)
        proposal = ProposalResponse.model_validate(data)
    except (ValidationError, PydanticSerializationError, ValueError, TypeError):
        raise ProposalDecisionError("invalid_proposal") from None
    if not proposal.proposal_saved:
        raise ProposalDecisionError("not_saved")
    if (
        payload.proposal_id != proposal.proposal_id
        or payload.base_commit_sha != proposal.base_commit_sha
        or payload.patch_sha256 != proposal.patch_sha256
    ):
        raise ProposalDecisionError("proposal_changed")

    created_at = datetime.now(timezone.utc) if now is None else now
    if (
        not isinstance(created_at, datetime) or created_at.tzinfo is None
        or created_at.utcoffset() is None or created_at < proposal.created_at
    ):
        raise ProposalDecisionError("invalid_time")
    return ProposalDecision(
        decision_id=uuid4().hex, proposal_id=proposal.proposal_id,
        investigation_run_id=proposal.investigation_run_id, account_id=identity.id,
        repository_id=proposal.repository_id, repository_full_name=proposal.repository_full_name,
        base_commit_sha=proposal.base_commit_sha, tree_sha=proposal.tree_sha,
        patch_sha256=proposal.patch_sha256, decision=payload.decision,
        created_at=created_at, comment=payload.comment,
    )
